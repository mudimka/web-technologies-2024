<?php
$cities = [
    "Московская область" => ["Москва", "Зеленоград", "Клин", "Королёв", "Красногорск"],
    "Ленинградская область" => ["Санкт-Петербург", "Всеволожск", "Павловск", "Кронштадт", "Кириши", "Кингисепп"],
    "Рязанская область" => ["Рязань", "Касимов", "Скопин", "Сасово", "Ряжск", "Кораблино"],
    "Нижегородская область" => ["Нижний Новгород", "Арзамас", "Дзержинск", "Бор", "Кстово"],
    "Новосибирская область" => ["Новосибирск", "Бердск", "Искитим", "Куйбышев", "Карасук", "Коченево"]
];

foreach ($cities as $region => $citiesList) {
    $filteredCities = array_filter($citiesList, function($city) {
        return mb_substr($city, 0, 1) === "К";
    });
    
    if (!empty($filteredCities)) {
        echo "$region:\n";
        echo implode(", ", $filteredCities) . ".\n\n";
    }
}
?>